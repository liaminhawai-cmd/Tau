// Bundles vendor/three (r169 ES modules) into one classic-script IIFE that
// exposes `window.THREE` — plus OrbitControls, MapControls and RoomEnvironment
// on the same global — so index.html can use the modern renderer without
// becoming an ES module page.
//   node scripts/build-three-global.mjs        (uses a local/npx esbuild)
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const args = [
  join(root, 'vendor/three/global-entry.js'),
  '--bundle', '--format=iife', '--global-name=THREE', '--minify', '--legal-comments=none',
  `--alias:three=${join(root, 'vendor/three/three.module.js')}`,
  `--outfile=${join(root, 'vendor/three/three.global.js')}`,
  '--banner:js=/* three.js r169 global build for Tau - generated by scripts/build-three-global.mjs */',
];
const bin = process.env.ESBUILD || 'npx';
const argv = bin === 'npx' ? ['-y', 'esbuild@0.24.0', ...args] : args;
execFileSync(bin, argv, { stdio: 'inherit' });
console.log('wrote vendor/three/three.global.js');

// Bundles vendor/pathtracer (three-gpu-pathtracer 0.0.23 + three-mesh-bvh 0.7.8 sources) into one
// classic-script IIFE that exposes `window.TAU_PT`, for the optional Ray tracing (Ultra) mode.
//   node scripts/build-pathtracer-global.mjs
//
// The game runs ONE three.js instance (window.THREE, from vendor/three/three.global.js). A second
// copy inside this bundle would give the tracer its own Material/BufferGeometry classes, and every
// instanceof check against the game's objects would fail — so `three` resolves to a generated shim
// that re-exports window.THREE's names instead of to three.module.js itself.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

// The repo carries no build dependencies of its own (three is bundled through `npx esbuild`), so
// fetch esbuild into a throwaway prefix rather than adding it to package.json.
async function loadEsbuild() {
  try { return await import('esbuild'); } catch (_) {}
  const dir = process.env.ESBUILD_DIR || mkdtempSync(join(tmpdir(), 'tau-esbuild-'));
  execFileSync('npm', ['i', '--no-save', '--no-audit', '--no-fund', '--prefix', dir, 'esbuild@0.24.0'],
    { stdio: 'inherit' });
  return import(pathToFileURL(join(dir, 'node_modules/esbuild/lib/main.js')).href);
}

// `const T = globalThis.THREE; export const Vector3 = T.Vector3; ...` for every name
// three.module.js exports, read off its single trailing `export { ... }` statement.
function threeShim() {
  const src = readFileSync(join(root, 'vendor/three/three.module.js'), 'utf8');
  const list = src.slice(src.lastIndexOf('\nexport {')).match(/export\s*\{([^}]*)\}/);
  if (!list) throw new Error('could not find the export list in vendor/three/three.module.js');
  const names = list[1].split(',').map(s => s.trim().split(/\s+as\s+/).pop()).filter(Boolean);
  return 'const T = globalThis.THREE;\n' +
    names.map(n => `export const ${n} = T.${n};`).join('\n') + '\n';
}

const resolveToThreeGlobal = {
  name: 'tau-three-global',
  setup(build) {
    build.onResolve({ filter: /^three$/ }, () => ({ path: 'three', namespace: 'tau-three' }));
    build.onLoad({ filter: /.*/, namespace: 'tau-three' }, () => ({ contents: threeShim(), loader: 'js' }));
    build.onResolve({ filter: /^three\/examples\/jsm\// }, args => ({
      path: join(root, 'vendor/three/addons',
        args.path.replace(/^three\/examples\/jsm\//, '').replace(/\.js$/, '') + '.js') }));
    build.onResolve({ filter: /^three-mesh-bvh$/ }, () => ({
      path: join(root, 'vendor/pathtracer/three-mesh-bvh/src/index.js') }));
    // Reached only from src/utils/UVUnwrapper.js, which nothing in the bundle imports. Stubbed so a
    // stray import can never drag a wasm module into a classic script.
    build.onResolve({ filter: /^xatlas-web$/ }, () => ({ path: 'xatlas-web', namespace: 'tau-stub' }));
    build.onLoad({ filter: /.*/, namespace: 'tau-stub' }, () => ({ contents: 'export default {};', loader: 'js' }));
  },
};

const esbuild = await loadEsbuild();
const outfile = join(root, 'vendor/pathtracer/pathtracer.global.js');
await esbuild.build({
  entryPoints: [join(root, 'vendor/pathtracer/global-entry.js')],
  bundle: true, format: 'iife', globalName: 'TAU_PT', minify: true, legalComments: 'none',
  target: 'es2020', outfile, plugins: [resolveToThreeGlobal],
  banner: { js: '/* three-gpu-pathtracer 0.0.23 + three-mesh-bvh 0.7.8 global build for Tau - generated by scripts/build-pathtracer-global.mjs */' },
});
console.log(`wrote vendor/pathtracer/pathtracer.global.js (${(statSync(outfile).size / 1024).toFixed(0)} kB)`);
